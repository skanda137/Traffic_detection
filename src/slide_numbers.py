"""Builds reports/slide_numbers.md from reports/*.csv; the one place slides copy numbers from."""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
REPORT_DIR = ROOT / "reports"
METRICS_PATH = REPORT_DIR / "phase2_final_metrics.csv"
ABLATION_PATH = REPORT_DIR / "ablation_and_seeds.csv"
SLICES_PATH = REPORT_DIR / "phase2_slices.csv"
QUANTILES_PATH = REPORT_DIR / "phase2_error_quantiles.csv"
OUTPUT_PATH = REPORT_DIR / "slide_numbers.md"
BASELINE_A = "baseline (a) per-hour median pace x distance"


def md_table(df: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def build() -> str:
    metrics = pd.read_csv(METRICS_PATH).set_index("model")
    if BASELINE_A not in metrics.index:
        raise ValueError(f"{BASELINE_A!r} missing from {METRICS_PATH.name}")
    base = metrics.loc[BASELINE_A]
    headline = pd.DataFrame({
        "model": metrics.index,
        "test RMSE (min)": metrics["rmse_min"].map("{:.2f}".format),
        "test MAE (min)": metrics["mae_min"].map("{:.2f}".format),
        "MAE / mean actual": metrics["mae_over_mean_actual"].map("{:.1%}".format),
        "RMSE improvement vs baseline (a)": (100 * (1 - metrics["rmse_min"] / base["rmse_min"])).map("{:+.1f}%".format),
        "MAE improvement vs baseline (a)": (100 * (1 - metrics["mae_min"] / base["mae_min"])).map("{:+.1f}%".format),
    })

    ablation = pd.read_csv(ABLATION_PATH, dtype={"seed": str})
    per_seed = ablation[~ablation["seed"].isin(["mean", "std"])]
    seeds = ", ".join(per_seed["seed"].unique())
    mean = ablation[ablation["seed"] == "mean"].set_index("model")
    std = ablation[ablation["seed"] == "std"].set_index("model")
    ablation_table = pd.DataFrame({
        "model": mean.index,
        "features": mean["n_features"].astype(int),
        "test RMSE (min)": [f"{mean.loc[m, 'rmse_min']:.2f} ± {std.loc[m, 'rmse_min']:.2f}" for m in mean.index],
        "test MAE (min)": [f"{mean.loc[m, 'mae_min']:.2f} ± {std.loc[m, 'mae_min']:.2f}" for m in mean.index],
        "RMSE improvement vs baseline (a)": [f"{mean.loc[m, 'rmse_improvement_pct']:.1f}% ± {std.loc[m, 'rmse_improvement_pct']:.1f}"
                                            for m in mean.index],
        "MAE improvement vs baseline (a)": [f"{mean.loc[m, 'mae_improvement_pct']:.1f}% ± {std.loc[m, 'mae_improvement_pct']:.1f}"
                                           for m in mean.index],
    })

    slices = pd.read_csv(SLICES_PATH, dtype={"value": str})
    peak = slices[slices["slice"] == "is_peak"].copy()
    peak["hours"] = peak["value"].map({"0": "off-peak", "1": "peak"})
    if peak["hours"].isna().any():
        raise ValueError(f"Unexpected is_peak values in {SLICES_PATH.name}: {peak['value'].unique().tolist()}")
    peak_table = pd.DataFrame({"model": peak["model"], "hours": peak["hours"], "test rows": peak["rows"],
                               "MAE (min)": peak["mae_min"].map("{:.2f}".format),
                               "MAE / mean actual": peak["mae_over_mean_actual"].map("{:.1%}".format)})

    quantiles = pd.read_csv(QUANTILES_PATH)
    interval_table = pd.DataFrame({
        "model": quantiles["model"],
        "q10 of actual/predicted": quantiles["q10_actual_over_predicted"].map("{:.3f}".format),
        "q90 of actual/predicted": quantiles["q90_actual_over_predicted"].map("{:.3f}".format),
        "80% interval": [f"[{a:.2f} × pred, {b:.2f} × pred]" for a, b in
                         zip(quantiles["q10_actual_over_predicted"], quantiles["q90_actual_over_predicted"])],
    })

    return "\n".join([
        "# Slide numbers",
        "",
        f"Generated by `src/slide_numbers.py` from `reports/{METRICS_PATH.name}`, `{ABLATION_PATH.name}`, "
        f"`{SLICES_PATH.name}` and `{QUANTILES_PATH.name}`. Do not edit by hand; rerun the script.",
        "",
        "## Test set: baselines vs models",
        "",
        md_table(headline),
        "",
        f"## Ablation across split seeds ({seeds}), mean ± std over seeds",
        "",
        md_table(ablation_table),
        "",
        "## Peak vs off-peak (test set)",
        "",
        md_table(peak_table),
        "",
        "## Empirical 80% interval factors (test set, marginal)",
        "",
        md_table(interval_table),
        "",
    ])


if __name__ == "__main__":
    text = build()
    OUTPUT_PATH.write_text(text, encoding="utf-8")
    print(text)
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)}")
